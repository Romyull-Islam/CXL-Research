"""Operation files for the real-SSD test (analysis/ssd_test.py): one int32 per operation, a unit index
u >= 0 for a write of unit u and -(u + 1) for a trim of unit u. Streams:
  lru_chat        LRU prefix cache, admit all (data/streams/lru_chat_all.npy)
  scoped_trim     KV kept per request, freed blocks trimmed when the request ends
  scoped_notrim   the same without trims (CXL.mem has no TRIM)
The sequential and uniform-random references are generated by ssd_test.py itself.
Run: python analysis/ssd_streams.py"""
import json
import sys
from collections import deque
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from lifetime_waf import request_scoped_stream  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "ssd"


def scoped(trim):
    ev = request_scoped_stream()
    live = peak = 0
    for _, kind, _, k in ev:
        live += 1 if kind == 0 else -k
        peak = max(peak, live)
    fifo, owned, ops = deque(range(peak)), {}, []
    for _, kind, rid, k in ev:
        if kind == 0:
            u = fifo.popleft()
            owned.setdefault(rid, []).append(u)
            ops.append(u)
        else:
            for u in owned.pop(rid, []):
                if trim:
                    ops.append(-(u + 1))
                fifo.append(u)
    return peak, np.array(ops, dtype=np.int32)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    lru = np.load(ROOT / "data" / "streams" / "lru_chat_all.npy").astype(np.int32)
    streams = {"lru_chat": (int(lru.max()) + 1, lru)}
    for name, trim in (("scoped_trim", True), ("scoped_notrim", False)):
        streams[name] = scoped(trim)
    meta = {}
    for name, (units, ops) in streams.items():
        ops.tofile(OUT / f"{name}.ops")
        meta[name] = dict(units=units, ops=len(ops), writes=int((ops >= 0).sum()), trims=int((ops < 0).sum()))
        print(name, meta[name], flush=True)
    (OUT / "streams.json").write_text(json.dumps(meta, indent=1))


if __name__ == "__main__":
    main()
